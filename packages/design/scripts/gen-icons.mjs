// Writes src/icons/paths.ts from lucide-static (ISC, src/icons/LICENSE.txt): the one line-icon set
// (24 grid; Icon draws it at stroke 1.5). The IconName union grows only here.
// Run: pnpm --filter @capybara-hq/design gen:icons
import { execFileSync } from "node:child_process";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(join(pkg, "package.json"));
const lucideDir = dirname(require.resolve("lucide-static/package.json"));
const { version } = JSON.parse(readFileSync(join(lucideDir, "package.json"), "utf8"));

/** The child elements of icons/<file>.svg as [tag, attrs] (Lucide's children are all self-closing). */
function readIcon(file) {
  const svg = readFileSync(join(lucideDir, "icons", `${file}.svg`), "utf8");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  return [...inner.matchAll(/<([a-z]+)\b([^>]*?)\/>/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries(
      [...attrs.matchAll(/([a-z][a-z0-9-]*)="([^"]*)"/g)].map(([, k, v]) => [k, v]),
    ),
  ]);
}

