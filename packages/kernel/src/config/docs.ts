import type { core } from "zod";
import { configFields, describeSchema } from "./fields.js";

/** `db.poolMax` -> `CAPYBARA_DB__POOL_MAX` (the inverse of the envOverrides mapping)。 */
export function envName(path: string): string {
  const seg = path.split(".").map((s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase());
  return `CAPYBARA_${seg.join("__")}`;
}

const cell = (s: string): string => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const code = (s: string): string => `\`${cell(s)}\``;

/** Default column: no default -> "required" ("optional" for optional fields); secret -> never printed (—). */
function defaultCell(secret: boolean, d: ReturnType<typeof describeSchema>): string {
  if (!d.hasDefault) return d.optional ? "optional" : "required";
  if (secret) return "—";
  const v =
    typeof d.defaultValue === "function" ? (d.defaultValue as () => unknown)() : d.defaultValue;
  return code(JSON.stringify(v) ?? "undefined");
}

/**
 * Renders the config schema as a deterministic Markdown table: dotted path, env var, type, default,
 * hot-reloadable, secret, description. The default of a secret field is always printed as "—" and
 * never reaches the document.
 */
export function renderConfigDocs(schema: core.$ZodType): string {
  const rows = configFields(schema).map((f) => {
    const d = describeSchema(f.schema);
    const secret = f.meta?.secret === true;
    return `| ${[
      code(f.path),
      code(envName(f.path)),
      code(d.type),
      defaultCell(secret, d),
      f.meta?.hot === true ? "yes" : "no",
      secret ? "yes" : "no",
      cell(f.meta?.description ?? ""),
    ].join(" | ")} |`;
  });
  return [
    "# Configuration reference",
    "",
    "<!-- Generated by `pnpm gen:config-docs`; do not edit by hand. -->",
    "",
    "The config source is chosen by `CAPYBARA_CONFIG_SOURCE` (`file` or `nacos`); environment variables win.",
    "Nested keys use double underscores, e.g. `CAPYBARA_DB__URL` maps to `db.url`.",
    "The defaults of secret fields do not appear in this document.",
    "",
    "| Key | Env var | Type | Default | Hot | Secret | Description |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "## Nacos config source",
    "",
    "With `CAPYBARA_CONFIG_SOURCE=nacos`, Nacos is specified by the following environment variables (they are not config keys and cannot be written in the config file):",
    "",
    "| Env var | Description |",
    "| --- | --- |",
    "| `CAPYBARA_NACOS_SERVER` | Nacos address (e.g. `nacos:8848`; the protocol defaults to http). Required |",
    "| `CAPYBARA_NACOS_NAMESPACE` | Namespace ID. Required |",
    "| `CAPYBARA_NACOS_DATA_ID` | The config's dataId (YAML). Required; the group is fixed to `DEFAULT_GROUP` |",
    "| `CAPYBARA_NACOS_USERNAME` / `CAPYBARA_NACOS_PASSWORD` | Username and password when Nacos has authentication on: the kernel logs in to obtain an accessToken and logs in again after 80% of `tokenTtl` or on a 403; set both or neither |",
    "| `CAPYBARA_NACOS_ACCESS_TOKEN` | An accessToken used as is (the login endpoint is not called); cannot be set together with the username and password |",
    "",
    // The web tier's env vars and defaults are owned by apps/web/src/lib/kernel-proxy.ts (kernel address,
    // body and package upload limits), apps/web/server.mjs (PORT / CAPYBARA_WEB_HOST) and
    // apps/web/src/dev/catalog/routes.tsx (CAPYBARA_DEV_UI); change this text together with them.
    // CAPYBARA_WEB_TRUST_PROXY: apps/web/src/lib/peer.ts; CAPYBARA_WEB_SHUTDOWN_GRACE_MS: apps/web/server.mjs.
    // CAPYBARA_WEB_OBJECT_STORE_*: apps/web/src/lib/object-store-proxy.ts.
    "## Web tier (apps/web) environment variables",
    "",
    "The web tier is a separate process (started through `apps/web/server.mjs`); it does not read the kernel config and only honors the following environment variables:",
    "",
    "| Env var | Description |",
    "| --- | --- |",
    "| `CAPYBARA_KERNEL_URL` | The kernel address that the `/api/*` proxy forwards to; default `http://localhost:8080` |",
    "| `PORT` / `CAPYBARA_WEB_HOST` | The web tier's listen port (default 3000) and address |",
    "| `CAPYBARA_WEB_TRUST_PROXY` | Proxies in front of the web tier (TLS proxy, load balancer) trusted to report the client address in `X-Forwarded-For`: a hop count (`1` = the nearest proxy) or a list of IPs / CIDRs, comma-separated or a JSON array, in the grammar of `http.trustProxy` (dotted netmasks, `loopback` / `linklocal` / `uniquelocal`; a range that trusts every address such as `/0` is refused; no `true` / `false`). Unset (default) trusts nothing: the socket peer is the client, so behind a proxy every user shares the proxy's address for login rate limiting. A hop count is only safe when the web tier is reachable solely through exactly that many proxies. Either way the kernel receives one sanitized client address; a malformed value stops the web tier at startup |",
    "| `CAPYBARA_WEB_SHUTDOWN_GRACE_MS` | Production only: after SIGTERM / SIGINT, how long in-flight requests (including SSE streams) may run before the process exits; default 5000 |",
    "| `CAPYBARA_WEB_MAX_BODY_BYTES` | Request body limit of the `/api/*` proxy, default 1 MiB (matches the kernel's bodyLimit) |",
    "| `CAPYBARA_WEB_MAX_PACKAGE_BYTES` | Request body limit for extension package, catalog package and plugin uploads (`/api/v1/admin/extensions/packages/file`, `/api/v1/admin/catalog/import/file`, `/api/v1/admin/catalog/plugins/prepare/file`), default 50 MiB, forwarded while being read. This is the web tier's limit; the kernel additionally rejects by `packages.maxBytes`. Raise both together, otherwise a large package uploaded through the web is first rejected by the web tier with a 413 |",
    "| `CAPYBARA_WEB_OBJECT_STORE_URL` | Object storage on the web origin: the object store's address as web reaches it (e.g. `http://seaweedfs-s3:8333`). When set, web proxies `/<bucket>/**` (and `/<bucket>` itself for POST only) there, so browsers upload attachments (presigned POST) and download attachments and artifacts (presigned GET) through web; set the object-store plugin's `publicEndpoint` to the web origin with `forcePathStyle: true`. Only GET, HEAD and POST; the path is forwarded unchanged; cookies and authorization are not forwarded; responses carry `X-Content-Type-Options: nosniff` and `Content-Security-Policy: sandbox`; uploads are capped at `CAPYBARA_WEB_MAX_PACKAGE_BYTES`. Unset (default): off |",
    "| `CAPYBARA_WEB_OBJECT_STORE_BUCKET` | With `CAPYBARA_WEB_OBJECT_STORE_URL`: the bucket, equal to the object-store plugin's `bucket` (it is the first path segment web proxies) |",
    "| `CAPYBARA_WEB_OBJECT_STORE_PUBLIC_HOST` | With `CAPYBARA_WEB_OBJECT_STORE_URL`: the host of the plugin's `publicEndpoint` (a host such as `capybara.example.com`, or that URL). Sent upstream as `Host` instead of the incoming one, because presigned URLs sign the host they were issued for and front proxies rewrite it |",
    "| `CAPYBARA_DEV_UI` | When set to `1`, production builds also serve the `/dev/ui` component catalog page (off by default) |",
    "",
  ].join("\n");
}
