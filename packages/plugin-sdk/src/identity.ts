/**
 * An external identity; login, channel inbound and directory all use the same (source, externalId)
 * key.
 */
export interface ExternalIdentity {
  /**
   * `"<plugin name>:<tenant id>"`, must equal `tenantId`. On third-party login the kernel checks
   * `source === \`${plugin name}:${tenantId}\``, and rejects a mismatch as an identity source
   * error.
   */
  source: string;
  externalId: string;
  tenantId: string;
  email?: string;
  emailVerified: boolean;
  displayName: string;
  avatarUrl?: string;
}

/**
 * Third-party login (`identity-source@1`). State, nonce and PKCE are all generated by the kernel
 * and kept server-side:
 * the plugin puts `codeChallenge` / `codeChallengeMethod` into the authorization URL
 * (`code_challenge` / `code_challenge_method`),
 * and passes `codeVerifier` (`code_verifier`) when exchanging the token at the callback. If the
 * platform does not support PKCE, just ignore these fields.
 */
export interface IdentitySource {
  label: { zh: string; en: string };
  authorizeUrl(args: {
    config: unknown;
    redirectUri: string;
    state: string;
    nonce: string;
    /**
     * PKCE challenge (base64url(SHA-256(codeVerifier))); the kernel always provides it, old kernels
     * do not.
     */
    codeChallenge?: string;
    /** The PKCE challenge algorithm; the kernel uses only `"S256"`. */
    codeChallengeMethod?: "S256";
  }): string;
  callback(args: {
    config: unknown;
    redirectUri: string;
    query: Record<string, string>;
    nonce: string;
    signal: AbortSignal;
    /**
     * The PKCE verifier matching this flow's `codeChallenge`; the kernel always provides it, old
     * kernels do not.
     */
    codeVerifier?: string;
  }): Promise<ExternalIdentity>;
}
