/**
 * An external identity; login, channel inbound and directory all use the same (source, externalId)
 * key.
 */
export interface ExternalIdentity {
  /**
   * `"<plugin name>:<tenant id>"`, must equal `tenantId`. On third-party login the kernel checks
   * `source === \`${plugin name}:${tenantId}\``, and rejects a mismatch as an identity source
   * error.
   */
  source: string;
  externalId: string;
  tenantId: string;
  email?: string;
  emailVerified: boolean;
  displayName: string;
  avatarUrl?: string;
}

/** How an identity source describes its tenants to the admin console. */
export interface IdentitySourceTenant {
  /** The field label, e.g. "Slack 工作区 ID" / "Slack workspace ID". */
  label: { zh: string; en: string };
  /** Where to find the tenant id. */
  help?: { zh: string; en: string };
  /** A regular expression (JavaScript syntax) a tenant id must match, e.g. `^T[A-Z0-9]+$`. */
  pattern?: string;
  /** An example tenant id shown as the placeholder. */
  placeholder?: string;
  /** Tenant ids that may never be trusted for email merge (Google: `consumer`). */
  neverTrusted?: string[];
}

/**
 * Checks a tenant id against a source's tenant declaration: `"empty"` for a blank id, `"pattern"`
 * when it does not match the declared pattern (an invalid pattern counts as none),
 * `"never_trusted"` when the source lists it in `neverTrusted`, else `"ok"`. The id is trimmed
 * first. The kernel uses it before storing trusted tenants.
 */
export function validateTenantId(
  decl: IdentitySourceTenant | undefined,
  id: string,
): "ok" | "pattern" | "never_trusted" | "empty" {
  const value = id.trim();
  if (value === "") return "empty";
  if (decl?.pattern) {
    let re: RegExp | undefined;
    try {
      re = new RegExp(decl.pattern);
    } catch {
      re = undefined;
    }
    if (re && !re.test(value)) return "pattern";
  }
  if (decl?.neverTrusted?.includes(value)) return "never_trusted";
  return "ok";
}

/**
 * Third-party login (`identity-source@1`). State, nonce and PKCE are all generated by the kernel
 * and kept server-side:
 * the plugin puts `codeChallenge` / `codeChallengeMethod` into the authorization URL
 * (`code_challenge` / `code_challenge_method`),
 * and passes `codeVerifier` (`code_verifier`) when exchanging the token at the callback. If the
 * platform does not support PKCE, just ignore these fields.
 */
export interface IdentitySource {
  label: { zh: string; en: string };
  /**
   * What a tenant is on this platform, so the admin console can label and check the trusted
   * tenants of this source (a tenant id is the `<tenant>` of the source key `<plugin>:<tenant>`).
   * Without it the console shows a plain tenant id field.
   */
  tenant?: IdentitySourceTenant;
  authorizeUrl(args: {
    config: unknown;
    redirectUri: string;
    state: string;
    nonce: string;
    /**
     * PKCE challenge (base64url(SHA-256(codeVerifier))); the kernel always provides it, old kernels
     * do not.
     */
    codeChallenge?: string;
    /** The PKCE challenge algorithm; the kernel uses only `"S256"`. */
    codeChallengeMethod?: "S256";
  }): string;
  callback(args: {
    config: unknown;
    redirectUri: string;
    query: Record<string, string>;
    nonce: string;
    signal: AbortSignal;
    /**
     * The PKCE verifier matching this flow's `codeChallenge`; the kernel always provides it, old
     * kernels do not.
     */
    codeVerifier?: string;
  }): Promise<ExternalIdentity>;
}

/**
 * Thrown by an identity source's `callback` when it refuses the account on purpose (a hosted domain
 * or tenant the platform does not allow, a consumer account where only organization accounts are
 * allowed): the login page then says the account is not allowed (`sso.account_not_allowed`) instead
 * of a provider error. The message is logged by the kernel and never shown to the person. Throw it
 * only after the response itself was verified (ID token, nonce, PKCE); every other failure stays a
 * plain error.
 */
export class IdentitySourceRefused extends Error {
  constructor(message: string) {
    super(message);
    this.name = "IdentitySourceRefused";
  }
}

/**
 * Whether `err` is an {@link IdentitySourceRefused}: any `Error` whose `name` is
 * `"IdentitySourceRefused"`, so a plugin that bundles another copy of the SDK still matches.
 */
export function isIdentitySourceRefused(err: unknown): boolean {
  return err instanceof Error && err.name === "IdentitySourceRefused";
}
