// Generates the client host shims (client extensions spec §9.4): the modules the import map points
// a client bundle's externals at (`react`, `react/jsx-runtime`, `react-dom`,
// `@capybara-hq/plugin-client`). Each re-exports, by name, from the global the web's ClientHost
// sets before it imports an entry (`globalThis.__CAPYBARA_CLIENT_HOST__`), and throws
// `capybara client host not ready` without it: React stays the one instance inside Next's chunks.
//
// Output (gitignored): public/_capybara/client-host/<webBuild>/{react,react-jsx-runtime,react-dom,
// plugin-client}.mjs and public/_capybara/client-host/manifest.json ({ "build": "<webBuild>",
// "integrity": { "<file>": "sha384-…" } }), which the workspace layout reads for the import map. `<webBuild>` is the web package version plus
// the first 12 hex digits of the sha256 of the shims, so a changed shim gets a new URL (they are
// served as immutable static files). Older builds' folders are removed.
//
// Run by `pnpm --filter @capybara-hq/web dev` / `build` (and `gen:client-host`); `--out <dir>`
// writes elsewhere (tests). Node 24 strips the types of the generated TypeScript list it imports.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PLUGIN_CLIENT_EXPORTS } from "../src/lib/client-host/api.generated.ts";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(web, "package.json"));

const outArg = process.argv.indexOf("--out");
const out =
  outArg !== -1 && process.argv[outArg + 1] !== undefined
    ? resolve(process.argv[outArg + 1])
    : join(web, "public", "_capybara", "client-host");

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
/** The named exports a shim re-exports: identifiers only, never `default`, sorted. */
const namesOf = (keys) => [...new Set(keys)].filter((k) => k !== "default" && IDENT.test(k)).sort();

/** One shim: `key` is the host global's member; `withDefault` adds `export default`. */
function shim(key, names, withDefault) {
  return [
    "// Generated by apps/web/scripts/gen-client-host.mjs; do not edit.",
    "const host = globalThis.__CAPYBARA_CLIENT_HOST__;",
    'if (host === undefined || host === null) throw new Error("capybara client host not ready");',
    `const m = host.${key};`,
    ...(withDefault ? ["export default m;"] : []),
    `export const { ${names.join(", ")} } = m;`,
    "",
  ].join("\n");
}

const shims = {
  "react.mjs": shim("react", namesOf(Object.keys(require("react"))), true),
  "react-jsx-runtime.mjs": shim(
    "jsxRuntime",
    namesOf(Object.keys(require("react/jsx-runtime"))),
    false,
  ),
  "react-dom.mjs": shim("reactDom", namesOf(Object.keys(require("react-dom"))), true),
  "plugin-client.mjs": shim("pluginClient", namesOf(PLUGIN_CLIENT_EXPORTS), false),
};

const { version } = JSON.parse(readFileSync(join(web, "package.json"), "utf8"));
const hash = createHash("sha256");
for (const [name, body] of Object.entries(shims)) hash.update(`${name}\n${body}\n`);
const build = `${version}-${hash.digest("hex").slice(0, 12)}`;

mkdirSync(out, { recursive: true });
for (const entry of readdirSync(out, { withFileTypes: true })) {
  if (entry.isDirectory() && entry.name !== build)
    rmSync(join(out, entry.name), { recursive: true });
}
mkdirSync(join(out, build), { recursive: true });
for (const [name, body] of Object.entries(shims)) writeFileSync(join(out, build, name), body);
// Each shim's sha384, for the import map's `integrity` (every module of the graph is verified).
const integrity = Object.fromEntries(
  Object.entries(shims).map(([name, body]) => [
    name,
    `sha384-${createHash("sha384").update(body).digest("base64")}`,
  ]),
);
writeFileSync(join(out, "manifest.json"), `${JSON.stringify({ build, integrity })}\n`);
console.log(`client host shims: ${build}`);
