import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import { renderCoverageBaseline, writeBaseline } from "../src/coverage-baseline.js";

it("groups kernel src files into module rows sorted by path", () => {
  const md = renderCoverageBaseline({
    total: { lines: { total: 3, covered: 2, pct: 66.6 } },
    "packages/kernel/src/runtime/a.ts": { lines: { total: 2, covered: 2, pct: 100 } },
    "packages/kernel/src/runtime/b.ts": { lines: { total: 1, covered: 0, pct: 0 } },
  });
  expect(md).toContain("| runtime | 3 | 2 | 66.7% |");
});

describe("renderCoverageBaseline", () => {
  it("accepts the absolute paths the json-summary reporter writes", () => {
    const md = renderCoverageBaseline({
      "/repo/packages/kernel/src/runtime/a.ts": { lines: { total: 2, covered: 2, pct: 100 } },
      "/repo/packages/kernel/src/runtime/b.ts": { lines: { total: 1, covered: 0, pct: 0 } },
      "packages/kernel/src/runtime/c.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    expect(md).toContain("| runtime | 4 | 3 | 75.0% |");
  });

  it("ignores absolute paths outside packages/kernel/src", () => {
    const md = renderCoverageBaseline({
      "/repo/packages/plugin-sdk/src/index.ts": { lines: { total: 5, covered: 0, pct: 0 } },
      "/repo/packages/kernel/test/a.test.ts": { lines: { total: 4, covered: 4, pct: 100 } },
      "/repo/packages/kernel/src/api/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    expect(md).toContain("| api | 1 | 1 | 100.0% |");
    expect(md).not.toContain("plugin-sdk");
    expect(md).not.toContain("| test |");
  });

  it("ignores the total entry and paths outside packages/kernel/src", () => {
    const md = renderCoverageBaseline({
      total: { lines: { total: 10, covered: 10, pct: 100 } },
      "packages/kernel/src/catalog/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/plugin-sdk/src/index.ts": { lines: { total: 5, covered: 0, pct: 0 } },
    });
    expect(md).toContain("| catalog | 1 | 1 | 100.0% |");
    expect(md).not.toContain("plugin-sdk");
    expect(md).not.toContain("| total |");
  });

  it("sorts module rows by key", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/runtime/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/kernel/src/catalog/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/kernel/src/api/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    const rows = md.split("\n").filter((line) => /^\| (api|catalog|runtime) \|/.test(line));
    expect(rows.map((row) => row.split("|")[1]?.trim())).toEqual(["api", "catalog", "runtime"]);
  });

  it("emits an em dash when a module has no lines", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/empty/a.ts": { lines: { total: 0, covered: 0, pct: 100 } },
    });
    expect(md).toContain("| empty | 0 | 0 | — |");
  });

  it("ends with the generation footer", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/api/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    expect(md.trimEnd().endsWith("Generated by pnpm coverage:baseline")).toBe(true);
  });
});

describe("writeBaseline", () => {
  let dir: string | undefined;

  function tempRoot(summary: unknown): string {
    dir = mkdtempSync(join(tmpdir(), "coverage-baseline-"));
    mkdirSync(join(dir, "coverage"), { recursive: true });
    writeFileSync(join(dir, "coverage", "coverage-summary.json"), JSON.stringify(summary));
    return dir;
  }

  afterEach(() => {
    if (dir !== undefined) rmSync(dir, { recursive: true, force: true });
    dir = undefined;
    vi.restoreAllMocks();
  });

  it("writes rows from the absolute paths the real reporter emits", () => {
    const root = tempRoot({
      total: { lines: { total: 3, covered: 2, pct: 66.6 } },
      "/repo/packages/kernel/src/runtime/a.ts": { lines: { total: 2, covered: 2, pct: 100 } },
      "/repo/packages/kernel/src/runtime/b.ts": { lines: { total: 1, covered: 0, pct: 0 } },
      "/repo/packages/plugin-sdk/src/index.ts": { lines: { total: 5, covered: 0, pct: 0 } },
    });
    vi.spyOn(console, "log").mockImplementation(() => {});
    writeBaseline(root);
    const out = readFileSync(join(root, "docs", "testing", "coverage-baseline.md"), "utf8");
    expect(out).toContain("| runtime | 3 | 2 | 66.7% |");
    expect(out).not.toContain("plugin-sdk");
  });

  it("fails instead of writing an empty baseline", () => {
    const root = tempRoot({
      total: { lines: { total: 5, covered: 0, pct: 0 } },
      "/repo/packages/plugin-sdk/src/index.ts": { lines: { total: 5, covered: 0, pct: 0 } },
    });
    expect(() => writeBaseline(root)).toThrow(
      /No packages\/kernel\/src entries in .*coverage-summary\.json/,
    );
    expect(existsSync(join(root, "docs", "testing", "coverage-baseline.md"))).toBe(false);
  });

  it("fails with an actionable message when the summary is missing", () => {
    dir = mkdtempSync(join(tmpdir(), "coverage-baseline-"));
    expect(() => writeBaseline(dir as string)).toThrow(
      /Cannot read .*coverage-summary\.json.*pnpm coverage/,
    );
  });
});
