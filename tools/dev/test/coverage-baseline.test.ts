import { describe, expect, it } from "vitest";
import { renderCoverageBaseline } from "../src/coverage-baseline.js";

it("groups kernel src files into module rows sorted by path", () => {
  const md = renderCoverageBaseline({
    total: { lines: { total: 3, covered: 2, pct: 66.6 } },
    "packages/kernel/src/runtime/a.ts": { lines: { total: 2, covered: 2, pct: 100 } },
    "packages/kernel/src/runtime/b.ts": { lines: { total: 1, covered: 0, pct: 0 } },
  });
  expect(md).toContain("| runtime | 3 | 2 | 66.7% |");
});

describe("renderCoverageBaseline", () => {
  it("ignores the total entry and paths outside packages/kernel/src", () => {
    const md = renderCoverageBaseline({
      total: { lines: { total: 10, covered: 10, pct: 100 } },
      "packages/kernel/src/catalog/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/plugin-sdk/src/index.ts": { lines: { total: 5, covered: 0, pct: 0 } },
    });
    expect(md).toContain("| catalog | 1 | 1 | 100.0% |");
    expect(md).not.toContain("plugin-sdk");
    expect(md).not.toContain("| total |");
  });

  it("sorts module rows by key", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/runtime/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/kernel/src/catalog/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
      "packages/kernel/src/api/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    const rows = md.split("\n").filter((line) => /^\| (api|catalog|runtime) \|/.test(line));
    expect(rows.map((row) => row.split("|")[1]?.trim())).toEqual(["api", "catalog", "runtime"]);
  });

  it("emits an em dash when a module has no lines", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/empty/a.ts": { lines: { total: 0, covered: 0, pct: 100 } },
    });
    expect(md).toContain("| empty | 0 | 0 | — |");
  });

  it("ends with the generation footer", () => {
    const md = renderCoverageBaseline({
      "packages/kernel/src/api/a.ts": { lines: { total: 1, covered: 1, pct: 100 } },
    });
    expect(md.trimEnd().endsWith("Generated by pnpm coverage:baseline")).toBe(true);
  });
});
