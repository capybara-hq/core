import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as pluginClient from "@capybara-hq/plugin-client";
import { UI_SLOTS } from "@capybara-hq/plugin-sdk";
import { checkSdkApi } from "./sdk-api.js";
import type { Finding } from "./source.js";
import { declareList } from "./ui-slots.js";

export type { Finding };

/** Where the generated web copy lives, relative to the repository root. */
export const PLUGIN_CLIENT_API_TS = "apps/web/src/lib/client-host/api.generated.ts";

/** The `packages/plugin-client` directory and its API report. */
export const PLUGIN_CLIENT_DIR = fileURLToPath(
  new URL("../../../packages/plugin-client", import.meta.url),
);
export const PLUGIN_CLIENT_API_REPORT_FILE = "api/plugin-client.api.md";

/** The design components the package forwards to the host (spec §4.2), sorted. */
export const DESIGN_SUBSET = [
  "Badge",
  "Button",
  "Icon",
  "Kbd",
  "KeyValue",
  "Logo",
  "PropertySection",
  "Spinner",
  "Stack",
  "Text",
  "Tooltip",
  "ViewBlocks",
] as const;

const COMPONENT_SLOT_IDS = UI_SLOTS.filter((s) => s.accepts.includes("component")).map((s) => s.id);

/** The runtime export names of the package: what the host's import-map module must provide. */
export function pluginClientExports(): string[] {
  return Object.keys(pluginClient).sort();
}

/** The generated web copy of the package's export list (the web never imports the package). */
export function renderPluginClientApiTs(
  exports: readonly string[] = pluginClientExports(),
  version: number = pluginClient.CLIENT_API_VERSION,
): string {
  return [
    "// Generated by pnpm gen:plugin-client from @capybara-hq/plugin-client; do not edit.",
    "",
    `export const CLIENT_API_VERSION = ${version};`,
    "",
    "/** Every runtime export of @capybara-hq/plugin-client (sorted): what the host module provides. */",
    declareList("export const PLUGIN_CLIENT_EXPORTS: readonly string[] = ", exports, ";"),
    "",
    "/** The design components a client bundle may use. */",
    declareList("export const DESIGN_SUBSET: readonly string[] = ", DESIGN_SUBSET, ";"),
    "",
    "/** The slots that accept `component`. */",
    declareList("export const COMPONENT_SLOT_IDS: readonly string[] = ", COMPONENT_SLOT_IDS, ";"),
    "",
  ].join("\n");
}

/** `plugin-client-api-stale`: the generated web copy differs from the package's export list. */
export function checkPluginClientApi(
  root: string,
  expected: string = renderPluginClientApiTs(),
): Finding[] {
  const file = join(root, PLUGIN_CLIENT_API_TS);
  const actual = existsSync(file) ? readFileSync(file, "utf8") : undefined;
  if (actual === expected) return [];
  const a = (actual ?? "").split("\n");
  const e = expected.split("\n");
  let line = 0;
  while (line < e.length && a[line] === e[line]) line++;
  return [
    {
      file,
      line: line + 1,
      rule: "plugin-client-api-stale",
      message:
        actual === undefined
          ? `${PLUGIN_CLIENT_API_TS} is missing; run pnpm gen:plugin-client`
          : `${PLUGIN_CLIENT_API_TS} differs from @capybara-hq/plugin-client; run pnpm gen:plugin-client (never edit it by hand)`,
    },
  ];
}

/** The package's public API report (api-extractor), as `plugin-client-api-stale` findings. */
export async function checkPluginClientApiReport(opts: { update: boolean }): Promise<Finding[]> {
  const findings = await checkSdkApi({
    ...opts,
    sdkDir: PLUGIN_CLIENT_DIR,
    reportFile: PLUGIN_CLIENT_API_REPORT_FILE,
  });
  return findings.map((f) => ({
    ...f,
    rule: "plugin-client-api-stale",
    message:
      "the plugin-client public API differs from packages/plugin-client/api/plugin-client.api.md; " +
      "run pnpm gen:plugin-client, commit the report and add a changeset for @capybara-hq/plugin-client",
  }));
}
